const DICTS: Record<Lang, Dict> = { en, km, vi, fr, th, zh };

const STORAGE_KEY = "ouk.lang";

function getInitialLang(): Lang {
  if (typeof window !== "undefined") {
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (stored && stored in DICTS) return stored;

      const browserLang = window.navigator?.language?.slice(0, 2).toLowerCase() as Lang;
      if (browserLang && browserLang in DICTS) return browserLang;
    } catch {
      // ignore
    }
  }
  return "vi";
}

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  ready: boolean;
};

const LangContext = createContext<Ctx>({
  lang: "vi",
  setLang: () => {},
  t: (k) => DICTS.vi[k] ?? DICTS.en[k] ?? k,
  ready: false,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(getInitialLang);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
    const initialLang = stored && stored in DICTS ? stored : getInitialLang();
    setLangState(initialLang);
    if (typeof document !== "undefined") {
      document.documentElement.lang = initialLang;
    }
    setReady(true);
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    if (typeof document !== "undefined") {
      document.documentElement.lang = l;
    }
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {
      // ignore
    }
  }, []);

  const t = useCallback((key: string) => DICTS[lang]?.[key] ?? DICTS.en[key] ?? key, [lang]);

  const value = useMemo(() => ({ lang, setLang, t, ready }), [lang, setLang, t, ready]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useI18n() {
  return useContext(LangContext);
}
